#!/usr/bin/env python3
"""Bundle src/compiler/ into one self-contained compile.py.

The submission contract is `python compile.py <ir> > out.ptx` with compile.py
at the repo root — the bundle guarantees that works even if the harness only
takes a single file. Dependency order: tables, emitter, analysis, algebra,
ops, stmts, smem, loops, passes, core.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ORDER = ["tables", "emitter", "analysis", "algebra", "ops",
         "stmts", "smem", "loops", "passes", "core"]

def module_src(name):
    return (ROOT / "src" / "compiler" / f"{name}.py").read_text()

def strip_rel_imports(text):
    """Drop any `from .x import ...` statement including parenthesized continuations."""
    res, skip = [], False
    for ln in text.split("\n"):
        if skip:
            if ")" in ln:
                skip = False
            continue
        if ln.startswith("from ."):
            if "(" in ln and ")" not in ln:
                skip = True
            continue
        res.append(ln)
    return "\n".join(res)

def main():
    out = ['#!/usr/bin/env python3',
           '"""Bundled single-file build of the src/compiler/ package.',
           'Source of truth: src/compiler/*.py (validated checkpoint f289d05).',
           'Generated by tools/bundle.py — do not edit by hand."""']
    seen_ext = set()
    for name in ORDER:
        text = module_src(name)
        text = strip_rel_imports(text)
        # keep external imports once, at the top
        keep = []
        for ln in text.split("\n"):
            m = re.match(r"^(import \w+|from (math|pathlib|emmy[.\w]*) import .*)", ln)
            if m:
                key = ln.strip()
                if key not in seen_ext:
                    seen_ext.add(key)
                    out.append(ln)
                continue
            keep.append(ln)
        body = "\n".join(keep)
        if name == "core":
            body = body.replace("tables.F32_ONLY", "F32_ONLY").replace(
                "tables.UNROLL_CAP", "UNROLL_CAP").replace(
                "tables.PURE_OPS", "PURE_OPS").replace(
                "tables.COMMUTATIVE", "COMMUTATIVE").replace(
                "tables._MEM_KINDS", "_MEM_KINDS").replace(
                "tables.CF_KINDS", "CF_KINDS")
        out.append("")
        out.append(body)
    # application layer: src/compiler/cli.py (main + find_kernel), relative
    # imports dropped (everything is in-file after the bundle)
    cli = strip_rel_imports(module_src("cli"))
    out.append("")
    out.append(cli)
    out.append('')
    out.append('if __name__ == "__main__":')
    out.append('    sys.exit(main())')
    sys.stdout.write("\n".join(out))

if __name__ == "__main__":
    main()
